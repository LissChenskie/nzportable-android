#!/usr/bin/env python3
"""Compile Vulkan 1.1 SPIR-V offline; generated C arrays are embedded in libmain."""
import argparse, pathlib, struct, subprocess
root = pathlib.Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--compiler', default='glslangValidator')
p.add_argument('--out', type=pathlib.Path, required=True)
a = p.parse_args()
a.out.parent.mkdir(parents=True, exist_ok=True)
lines = ['// Generated by compile_vulkan_shaders.py. Do not edit.']
# (stage, array name, extra defines). frag_mrt also writes motion vectors for the upscaler.
for source, name, defines in (('vril.vert', 'vert', []), ('vril.frag', 'frag', []), ('vril.frag', 'frag_mrt', ['MRT=1']),
                              ('lite.vert', 'lite_vert', []), ('lite.frag', 'lite_frag', [])):
    src = root / 'android/native/vulkan/shaders' / source
    binary = a.out.with_suffix('.' + name + '.spv')
    if 'glslc' in pathlib.Path(a.compiler).name:
        cmd = [a.compiler, '--target-env=vulkan1.1', '-O'] + ['-D' + d for d in defines] + [str(src), '-o', str(binary)]
    else:
        cmd = [a.compiler, '-V', '--target-env', 'vulkan1.1', '-Os'] + ['-D' + d for d in defines] + [str(src), '-o', str(binary)]
    subprocess.run(cmd, check=True)
    data = binary.read_bytes()
    words = struct.unpack('<' + 'I' * (len(data)//4), data)
    lines += [f'static const uint32_t nzp_vk_{name}[] = {{',
              ','.join(hex(v) for v in words), '};']
a.out.write_text('\n'.join(lines)+'\n')
